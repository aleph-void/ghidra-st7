#!/usr/bin/env python3
"""Generates the conditional-branch part of cases.txt. Conditions are taken from the manual's JRxx
table (PM0002, p.53); every opcode is run with its condition true and false."""
# (mnemonic, opcode, cond-true setup, cond-false setup, languages)  setup = {register: value}
T = [
    ('jra', 0x20, {}, None),
    ('jrf', 0x21, None, {}),
    ('jrugt', 0x22, {'C': 0, 'Z': 0}, {'C': 1, 'Z': 0}),
    ('jrugt', 0x22, None, {'C': 0, 'Z': 1}),
    ('jrule', 0x23, {'C': 1, 'Z': 0}, {'C': 0, 'Z': 0}),
    ('jrule', 0x23, {'C': 0, 'Z': 1}, None),
    ('jrnc', 0x24, {'C': 0}, {'C': 1}),
    ('jrc', 0x25, {'C': 1}, {'C': 0}),
    ('jrne', 0x26, {'Z': 0}, {'Z': 1}),
    ('jreq', 0x27, {'Z': 1}, {'Z': 0}),
    ('jrnh', 0x28, {'H': 0}, {'H': 1}),
    ('jrh', 0x29, {'H': 1}, {'H': 0}),
    ('jrpl', 0x2A, {'N': 0}, {'N': 1}),
    ('jrmi', 0x2B, {'N': 1}, {'N': 0}),
    ('jrih', 0x2F, {'EXTI': 1}, {'EXTI': 0}),
    ('jril', 0x2E, {'EXTI': 0}, {'EXTI': 1}),
]
M70 = [('jrnm', 0x2C, {'I': 0}, {'I': 1}), ('jrm', 0x2D, {'I': 1}, {'I': 0})]
M72 = [('jrnm', 0x2C, {'I0': 0, 'I1': 0}, {'I0': 1, 'I1': 0}),
       ('jrnm', 0x2C, None, {'I0': 0, 'I1': 1}),
       ('jrm', 0x2D, {'I0': 1, 'I1': 1}, {'I0': 0, 'I1': 1}),
       ('jrm', 0x2D, None, {'I0': 1, 'I1': 0})]

def emit(rows, only):
    n = 0
    for mn, op, true, false in rows:
        for taken, setup in ((True, true), (False, false)):
            if setup is None:
                continue
            n += 1
            print(f'case br_{mn}_{"taken" if taken else "not_taken"}_{n}' + (f' only {only}' if only else ''))
            print(f'code {op:02X}014C')   # jrxx +1 ; inc A  (end 0x1004 ... see until)
            print('until 1003')
            for r, v in setup.items():
                print(f'set {r} {v}')
            print(f'expect A {0 if taken else 1}')
            print('end\n')

print('# ---- conditional branches (generated by gen_branch_cases.py) ----')
emit(T, '')
emit(M70, 'st70')
emit(M72, 'st72')
